import { CloseIcon } from './icons'

/**
 * Политика конфиденциальности. Требование App Store (и почти любого стора):
 * должна быть доступна по публичному адресу, без входа в аккаунт — ревьюер
 * открывает её просто по ссылке. Поэтому App показывает эту страницу по пути
 * /privacy раньше, чем проверяет авторизацию.
 *
 * Текст описывает то, что действительно делает код. Прежде чем публиковать,
 * заполните значения в OPERATOR — без них страница честно говорит, что оператор
 * не указан, а не выдумывает название компании.
 *
 * Это не юридическая консультация: описание фактов, а не проверенный юристом
 * документ. Если приложение выходит за пределы личного использования, документ
 * стоит показать юристу — особенно в части GDPR и локальных законов.
 */
const OPERATOR = {
  /** Например: «ИП Иванов И. И.» или «Иван Иванов, частное лицо». */
  name: '',
  /** Адрес для запросов о данных и жалоб. Обязателен для App Store. */
  email: '',
  /** Страна, чьим законом регулируется обработка. */
  jurisdiction: '',
  /** Дата последнего изменения этого текста. */
  updated: '2026-08-09',
}

function Placeholder({ what }: { what: string }) {
  return <mark className="privacy-placeholder">не указано: {what}</mark>
}

export function PrivacyPolicy({ onClose }: { onClose?: () => void }) {
  return (
    <div className="privacy-page">
      <div className="privacy-sheet">
        <header className="privacy-header">
          <div>
            <h1>Политика конфиденциальности</h1>
            <p className="privacy-updated">Обновлено: {OPERATOR.updated}</p>
          </div>
          {onClose && (
            <button className="icon-btn" onClick={onClose} aria-label="Закрыть">
              <CloseIcon width={18} height={18} />
            </button>
          )}
        </header>

        <section>
          <h2>Кто обрабатывает данные</h2>
          <p>
            Оператор сервиса CorNet — {OPERATOR.name || <Placeholder what="название оператора" />}. Связаться по
            вопросам о данных, а также по жалобам на контент:{' '}
            {OPERATOR.email ? <a href={`mailto:${OPERATOR.email}`}>{OPERATOR.email}</a> : <Placeholder what="адрес для связи" />}.
            Применимое право: {OPERATOR.jurisdiction || <Placeholder what="юрисдикция" />}.
          </p>
        </section>

        <section>
          <h2>Что хранится</h2>
          <ul>
            <li>
              <strong>Аккаунт.</strong> Имя пользователя и пароль. Пароль хранится только в виде хеша (scrypt) —
              восстановить из него исходный пароль нельзя.
            </li>
            <li>
              <strong>Профиль.</strong> То, что вы заполнили сами: отображаемое имя, описание, статус, дата рождения,
              оформление профиля. Все поля необязательные.
            </li>
            <li>
              <strong>Почта.</strong> Только если вы её привязали — для подтверждения и восстановления доступа.
            </li>
            <li>
              <strong>Двухфакторная аутентификация.</strong> Секрет хранится зашифрованным (AES-256-GCM), резервные
              коды — в виде хешей.
            </li>
            <li>
              <strong>Сессии.</strong> Хеш токена сессии, строка браузера или приложения (User-Agent), время создания и
              последней активности. Список видно в настройках, любую сессию можно отозвать.
            </li>
            <li>
              <strong>Сообщения и чаты.</strong> Тексты, вложения, реакции, опросы, состав участников, отметки о
              прочтении, папки и настройки чатов.
            </li>
            <li>
              <strong>Звонки.</strong> Факт звонка, участники, время, длительность и итог (принят, пропущен, отклонён).
              Содержимое разговора не записывается и не сохраняется.
            </li>
            <li>
              <strong>Ключи шифрования.</strong> На сервере — только ваши <em>публичные</em> ключи. Приватные ключи
              никогда не покидают устройство.
            </li>
          </ul>
        </section>

        <section>
          <h2>Что сервер видит, а чего не видит</h2>
          <p>
            В чатах со сквозным шифрованием сервер хранит только шифротекст: прочитать переписку он не может, потому
            что приватных ключей у него нет. В остальных чатах текст сообщений хранится в открытом виде — иначе его
            нельзя было бы показать вам при входе с нового устройства.
          </p>
        </section>

        <section>
          <h2>Файлы</h2>
          <p>
            В зашифрованных чатах вложения шифруются на устройстве отдельным ключом, и на сервер уезжают
            непрозрачные байты под обезличенным именем. Настоящее имя файла, его тип и ключ едут внутри
            зашифрованного сообщения — сервер не видит ни того, ни другого, ни содержимого. Ему остаются размер файла,
            время загрузки и категория вложения (фото, видео, голосовое, документ) — она нужна, чтобы показать
            сообщение до расшифровки.
          </p>
          <p>
            В незашифрованных чатах файлы лежат как есть. Они хранятся под непредсказуемыми именами и отдаются только
            авторизованным пользователям, но отдельной проверки «этот файл именно из вашего чата» нет: любой вошедший в
            сервис пользователь, знающий точную ссылку, сможет файл открыть. Ссылки не индексируются и никому не
            выдаются, но это стоит учитывать для по-настоящему чувствительных документов.
          </p>
        </section>

        <section>
          <h2>Уведомления</h2>
          <p>
            Если вы включили уведомления, на сервере сохраняется идентификатор устройства, выданный Apple (APNs) или
            push-службой вашего браузера. Он привязан к сессии и удаляется вместе с ней — при выходе, отзыве сессии или
            смене пароля. В самом уведомлении отправляется имя отправителя и текст сообщения; для зашифрованных чатов
            текст не передаётся, потому что сервер его не знает. Показ текста можно выключить в настройках.
          </p>
        </section>

        <section>
          <h2>Звонки</h2>
          <p>
            Звонки идут напрямую между устройствами (WebRTC) и шифруются на уровне протокола. Чтобы соединение
            установилось, устройства обмениваются сетевыми адресами через STUN-серверы — по умолчанию публичные
            серверы Google, которые при этом видят ваш IP-адрес. Если оператор настроил собственный TURN-сервер, через
            него может идти и сам поток — уже зашифрованным.
          </p>
        </section>

        <section>
          <h2>Технические записи</h2>
          <p>
            Сервер ведёт журнал действий: метод и путь запроса, код ответа, идентификатор пользователя и длительность
            обработки. Содержимое сообщений в журнал не попадает. IP-адреса используются для ограничения частоты
            запросов (защита от подбора пароля и спама) и могут попадать в журналы хостинга.
          </p>
        </section>

        <section>
          <h2>Кому передаются данные</h2>
          <p>Сервис не продаёт данные и не передаёт их рекламным сетям. Данные проходят через:</p>
          <ul>
            <li>хостинг-провайдера, на котором работает сервер и база данных;</li>
            <li>почтовый сервис — если вы привязали почту (письма подтверждения и восстановления);</li>
            <li>Apple и push-службы браузеров — при доставке уведомлений;</li>
            <li>STUN/TURN-серверы — при установлении звонка.</li>
          </ul>
          <p>Шрифты и другие ресурсы загружаются с самого сервера, сторонней аналитики и трекеров в приложении нет.</p>
        </section>

        <section>
          <h2>Сколько хранится</h2>
          <ul>
            <li>Сообщения — пока вы их не удалите; в чатах с таймером исчезновения удаляются автоматически.</li>
            <li>Сессии — до 30 дней с момента входа, не более восьми одновременно.</li>
            <li>Ссылки для подтверждения почты — 24 часа, для восстановления пароля — 1 час.</li>
            <li>Жалобы — пока их не рассмотрит оператор, затем остаются в архиве обращений.</li>
          </ul>
        </section>

        <section>
          <h2>Удаление аккаунта</h2>
          <p>
            Настройки → Безопасность → «Удаление аккаунта». Удаляются профиль, сообщения, ключи, сессии, устройства для
            уведомлений и загруженные вами файлы. Личные переписки удаляются целиком, у обеих сторон. Группы
            продолжают существовать у остальных участников — исчезают только ваши сообщения. Действие необратимо.
          </p>
        </section>

        <section>
          <h2>Жалобы на контент</h2>
          <p>
            На любое сообщение и на любого пользователя можно пожаловаться: контекстное меню сообщения → «Пожаловаться»
            или карточка профиля → «Пожаловаться». Жалобы рассматривает оператор; нарушающий контент и аккаунты
            удаляются. Автор не узнаёт, что на него пожаловались. Кроме того, любого пользователя можно заблокировать —
            после этого сообщения и звонки от него не доходят.
          </p>
        </section>

        <section>
          <h2>Ваши права</h2>
          <p>
            Вы можете получить копию своих данных, исправить их или потребовать удаления — часть этого доступна прямо в
            приложении, остальное по запросу на адрес оператора выше. Если применимо законодательство ЕС (GDPR), у вас
            также есть право на возражение против обработки и право на жалобу в надзорный орган.
          </p>
        </section>

        <section>
          <h2>Дети</h2>
          <p>
            Сервис не предназначен для детей младше 13 лет. Если выяснится, что аккаунт принадлежит ребёнку младше
            указанного возраста, он будет удалён.
          </p>
        </section>

        <section>
          <h2>Изменения</h2>
          <p>
            Текст может меняться вместе с приложением. Дата последнего изменения указана вверху страницы; о
            существенных изменениях оператор сообщает в приложении.
          </p>
        </section>
      </div>
    </div>
  )
}
